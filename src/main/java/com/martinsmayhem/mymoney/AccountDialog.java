    /** Fills the parent list: "(none)" first, then accounts that can hold envelopes. */
    private void loadParents() {
        DefaultComboBoxModel<Account> model = new DefaultComboBoxModel<>();
        model.addElement(null);                         // null = top-level account
        try {
            for (Account a : accounts.findParentCandidates()) {
                model.addElement(a);
            }
        } catch (SQLException e) {
            showError("Could not load accounts:\n" + e.getMessage());
        }
        parentCombo.setModel(model);
        parentCombo.setRenderer(new DefaultListCellRenderer() {
            @Override
            public Component getListCellRendererComponent(JList<?> list, Object value,
                    int index, boolean isSelected, boolean cellHasFocus) {
                super.getListCellRendererComponent(list, value, index, isSelected, cellHasFocus);
                if (value == null) {
                    setText("(none - top-level account)");
                }
                return this;
            }
        });
    }

