    private void createButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_createButtonActionPerformed
        String name = nameField.getText().trim();
        if (name.isEmpty()) {
            showError("Please enter an account name.");
            return;
        }
        Account parent = (Account) parentCombo.getSelectedItem();
        AccountType type = (AccountType) typeCombo.getSelectedItem();
        if (type == AccountType.ENVELOPE && parent == null) {
            showError("An envelope must belong to a parent account.");
            return;
        }

        long openingCents;
        String amount = openingField.getText().trim();
        try {
            openingCents = amount.isEmpty() ? 0 : Money.parse(amount);
        } catch (IllegalArgumentException e) {
            showError(e.getMessage());
            return;
        }

        try {
            if (accounts.nameExists(name)) {
                showError("An account with that name already exists.");
                return;
            }
            createdAccountId = accounts.insert(name, type, openingCents,
                    parent == null ? null : parent.id());
        } catch (SQLException e) {
            showError("Could not create the account:\n" + e.getMessage());
            return;
        }
        dispose();
    }//GEN-LAST:event_createButtonActionPerformed

    private void parentComboActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_parentComboActionPerformed
        boolean hasParent = parentCombo.getSelectedItem() != null;
        if (hasParent) {
            typeCombo.setSelectedItem(AccountType.ENVELOPE);
        } else if (typeCombo.getSelectedItem() == AccountType.ENVELOPE) {
            typeCombo.setSelectedItem(AccountType.CHECKING);
        }
        typeCombo.setEnabled(!hasParent);           // envelopes are always type Envelope
    }//GEN-LAST:event_parentComboActionPerformed

